#!/usr/bin/env python3
"""Synchronize and propagate version information across Cmdiqo.

Single Source of Truth:
- version.txt in the repository root holds the true baseline version (e.g. 1.0.0).

Build Version Resolution:
- On GitHub Actions (GITHUB_SHA is present):
    VERSION = <major>.<minor>.<SHORT_GIT_SHA> (e.g. 1.0.a1b2c3d4)
- On Local Builds (GitHub build ID not present):
    VERSION = <major>.<minor>.devel+<HEX_TIMESTAMP> (e.g. 1.0.devel+6A9C0B2D)
- Explicit override via --version:
    VERSION = <override_version>

Propagates the resolved build version to:
- agent/_version.py
- bot/_version.py
- slacksim/_version.py
- agent/version_info.txt (Windows PE resource manifest for PyInstaller)
"""

from __future__ import annotations

import argparse
import os
import re
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VERSION_TXT = ROOT / "version.txt"
AGENT_VERSION_PY = ROOT / "agent" / "_version.py"
BOT_VERSION_PY = ROOT / "bot" / "_version.py"
SLACKSIM_VERSION_PY = ROOT / "slacksim" / "_version.py"
AGENT_VERSION_INFO = ROOT / "agent" / "version_info.txt"


def get_base_version() -> str:
    """Read base version from version.txt (the single source of truth)."""
    if VERSION_TXT.exists():
        raw = VERSION_TXT.read_text(encoding="utf-8").strip()
        m = re.match(r"^(\d+\.\d+(?:\.\d+)?)", raw)
        if m:
            return m.group(1)
        if raw:
            return raw
    return "1.0.0"


def generate_version_info_txt(
    version: str, numeric_version: tuple[int, int, int, int]
) -> str:
    """Generate PyInstaller VSVersionInfo structure for Windows PE executable."""
    major, minor, patch, build = numeric_version
    return f"""# UTF-8
# Windows Version Information Resource for cmdiqo-agent.exe
# Automatically generated by development/update_version.py. Do not edit manually.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers=({major}, {minor}, {patch}, {build}),
    prodvers=({major}, {minor}, {patch}, {build}),
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo(
      [
        StringTable(
          '040904b0',
          [
            StringStruct('CompanyName', 'Jaroslav Lhotak'),
            StringStruct('FileDescription', 'Cmdiqo LAN Remote Agent'),
            StringStruct('FileVersion', '{version}'),
            StringStruct('InternalName', 'cmdiqo-agent'),
            StringStruct('LegalCopyright', 'Copyright (c) 2026 Jaroslav Lhotak. Verified GitHub build.'),
            StringStruct('OriginalFilename', 'cmdiqo-agent.exe'),
            StringStruct('ProductName', 'Cmdiqo Agent'),
            StringStruct('ProductVersion', '{version}'),
          ]
        )
      ]
    ),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def update_versions(
    override_version: str | None = None,
    timestamp: int | None = None,
    silent: bool = False,
) -> str:
    """Resolve build version and propagate to internal Python modules and PE metadata."""
    base = get_base_version()
    parts = base.split(".")
    major = parts[0] if len(parts) > 0 else "1"
    minor = parts[1] if len(parts) > 1 else "0"

    github_sha = os.environ.get("GITHUB_SHA", "").strip()

    if override_version:
        version = override_version.strip()
        dev_match = re.match(r"^(\d+)\.(\d+)\.devel\+([0-9A-Fa-f]+)$", version)
        if dev_match:
            pe_tuple = (
                int(dev_match.group(1)),
                int(dev_match.group(2)),
                int(dev_match.group(3), 16) & 0xFFFF,
                0,
            )
        elif sha_match := re.match(r"^(\d+)\.(\d+)\.([0-9A-Fa-f]{7,40})$", version):
            pe_tuple = (
                int(sha_match.group(1)),
                int(sha_match.group(2)),
                int(sha_match.group(3)[-4:], 16),
                0,
            )
        else:
            digits = [int(m) for m in re.findall(r"\d+", version)]
            while len(digits) < 4:
                digits.append(0)
            pe_tuple = (digits[0], digits[1], digits[2], digits[3])
    elif github_sha:
        short_sha = github_sha[:12]
        version = f"{major}.{minor}.{short_sha}"
        pe_tuple = (int(major), int(minor), int(short_sha[-4:], 16), 0)
    else:
        # Local builds use the two-part baseline plus a hex timestamp.
        ts = int(time.time()) if timestamp is None else timestamp
        hex_ts = f"{ts:X}"
        version = f"{major}.{minor}.devel+{hex_ts}"
        pe_tuple = (int(major), int(minor), ts & 0xFFFF, 0)

    short_version = f"{major}.{minor}"

    # Write Python runtime version files (_version.py)
    py_content = (
        "# Generated automatically by development/update_version.py. Do not edit manually.\n"
        f'__version__ = "{version}"\n'
    )
    for py_file in (
        AGENT_VERSION_PY,
        BOT_VERSION_PY,
        SLACKSIM_VERSION_PY,
    ):
        py_file.write_text(py_content, encoding="utf-8")

    # Write Windows PE version_info.txt
    AGENT_VERSION_INFO.write_text(
        generate_version_info_txt(version, pe_tuple), encoding="utf-8"
    )

    if not silent:
        print(
            f"\033[0;32m[INFO]\033[0m Version synchronized: \033[34m{version}\033[0m (Short: {short_version})"
        )
        print(f"\033[0;32m[INFO]\033[0m PE Tuple: {pe_tuple}")

    return version


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Update and propagate project version numbers."
    )
    parser.add_argument("-v", "--version", help="Explicit version override")
    parser.add_argument(
        "--dev",
        action="store_true",
        help="Force development build with hex timestamp (default for local builds)",
    )
    parser.add_argument(
        "--print-version",
        action="store_true",
        help="Print only the resolved version string to stdout",
    )
    args = parser.parse_args()

    version = update_versions(
        override_version=args.version,
        silent=args.print_version,
    )
    if args.print_version:
        print(version)


if __name__ == "__main__":
    main()
